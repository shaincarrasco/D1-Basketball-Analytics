"""`python -m engine.paper_bets`: write docs/tennis-paper-bets.md from the betting backtest.

Simulation only: flat 1 unit on the side with the best model edge against historical closing odds, out-of-sample
predictions only. Not part of the site. With no odds in the database the report says so and explains how to import them.
"""
from __future__ import annotations

import argparse
import json
import math
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

from .db import ROOT

OUT = ROOT.parent.parent.parent / "docs" / "tennis-paper-bets.md"
BACKTEST = ROOT / "data" / "backtest.json"
Z = 1.96


def wilson(w: int, n: int) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = w / n
    d = 1 + Z * Z / n
    c = (p + Z * Z / (2 * n)) / d
    h = Z * math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def read_of(n: int) -> str:
    return "too few to read" if n < 100 else "early, wide range" if n < 300 else "readable, still noisy"


def units(x: float) -> str:
    return f"{'+' if x > 0 else '−' if x < 0 else ''}{abs(x):.2f}u"


def pct(x: float, signed: bool = False) -> str:
    s = f"{abs(x) * 100:.1f}%"
    return (("+" if x > 0 else "−" if x < 0 else "") + s) if signed else (("−" if x < 0 else "") + s)


def row(label: str, bets: list[dict]) -> str:
    n = len(bets)
    if n == 0:
        return f"| {label} | 0 | 0-0 | – | – | 0.00u | – | no bets |"
    w = sum(1 for b in bets if b["won"])
    prof = [b["profit"] for b in bets]
    lo, hi = wilson(w, n)
    roi = sum(prof) / n
    if n > 1:
        sd = math.sqrt(sum((x - roi) ** 2 for x in prof) / (n - 1))
        half = Z * sd / math.sqrt(n)
        roi_txt = f"{pct(roi, True)} ({pct(roi - half, True)} to {pct(roi + half, True)})"
    else:
        roi_txt = pct(roi, True)
    be = sum(1 / b["odds"] for b in bets) / n
    return (f"| {label} | {n} | {w}-{n - w} | {pct(w / n)} ({pct(lo)} to {pct(hi)}) | {pct(be)} | {units(sum(prof))} "
            f"| {roi_txt} | {read_of(n)} |")


HEAD = "| Slice | Bets | W-L | Win % (95% range) | Break-even | Units | ROI (95% range) | Read |\n| --- | --- | --- | --- | --- | --- | --- | --- |"
DISCLAIMER = ("**Simulation only. No real money is involved, this file is not part of the site, and nothing here predicts or "
              "guarantees future results.**")


def no_odds_report(bt: dict, stamp: str, odds_rows: Optional[int]) -> str:
    ov = bt.get("overall") or {}
    acc = f"{ov['accuracy'] * 100:.1f}%" if ov.get("accuracy") is not None else "n/a"
    return f"""# Tennis paper bets: Deuce vs the sportsbook

{DISCLAIMER}

Regenerated by `python -m engine.paper_bets` (in `apps/tennis/deuce/`). Backtest data from {stamp}. Flat 1 unit per bet.

## No odds yet

There are no historical odds in the database, so there is nothing to bet against and no paper bets to show. The
probability side of the model is still tested: {acc} of {ov.get('n', 'n/a')} out-of-sample matches picked right (see the
Model page on the site).{f' Odds rows in the database: {odds_rows}.' if odds_rows is not None else ''}

How odds get imported:

- **Historical closing odds (free, ATP and WTA tour level).** `python -m engine.odds_history` downloads the yearly
  files from tennis-data.co.uk, keeps a compact extract of each in `apps/tennis/deuce/data-cache/odds/tennis-data/`, and
  matches them to our matches. The deploy workflow refreshes them weekly; if the download is blocked, drop the yearly
  `.xlsx` files into `apps/tennis/deuce/data/odds_import/` and run it again. Every run of `engine.update` re-applies the
  stored extracts.
- **Challenger and ITF odds.** The OddsPapi source (free key, 250 requests a month) adds pre-match and closing odds for
  those tiers once `ODDSPAPI_KEY` is set; its records are stored in `data-cache/odds/records/`.
- **Live odds for the local dashboard.** Type them into a match's Odds tab, or set a free The Odds API key in `config.toml`.

Once odds are in, rerun `python -m engine.backtest` then `python -m engine.paper_bets` and this file fills in with
value bets, slices, a baseline comparison and the last 25 settled bets. Samples under 100 bets are labelled "too few to read".
"""


def report(bt: dict, stamp: str, odds_rows: Optional[int] = None) -> str:
    b, bets = bt.get("betting"), bt.get("bets") or []
    if not b or not bets:
        return no_odds_report(bt, stamp, odds_rows)
    thr = b.get("edge_threshold", 0.02)
    main = [x for x in bets if x["edge"] >= thr]
    lines = [
        "# Tennis paper bets: Deuce vs the sportsbook", "", DISCLAIMER, "",
        f"Regenerated by `python -m engine.paper_bets`. Backtest data from {stamp}. Flat 1 unit per bet on the side with the "
        f"best model edge against historical closing odds ({b.get('odds_source', 'n/a')}), strictly out-of-sample predictions. "
        f"Pre-set edge threshold: {thr * 100:.0f} points. Retirements are voided ({b.get('voided_retirement_bets', 0)} bets). "
        "Matches where either player has under 15 matches on record are never bet.", "",
        "## Headline", "", HEAD, row(f"Edge ≥ {thr * 100:.0f} pts (pre-set)", main), "",
        f"Matches with odds in the test: {b.get('matches_with_odds', 'n/a')}. Anything under 100 bets is too few to read; "
        "ranges are 95% and ignore that odds and model were tuned on the same seasons.", "",
        "## Slices", "", HEAD]
    for t in (0.0, 0.02, 0.05, 0.10):
        lines.append(row(f"Edge ≥ {t * 100:.0f} pts", [x for x in bets if x["edge"] >= t]))
    lines.append(row("Picked the favourite (model prob ≥ 50%)", [x for x in main if x["prob"] >= 0.5]))
    lines.append(row("Picked the underdog", [x for x in main if x["prob"] < 0.5]))
    for key, title in (("tour", "Tour"), ("level", "Level"), ("surface", "Surface")):
        for v in sorted({x[key] for x in main if x.get(key)}):
            lines.append(row(f"{title}: {v}", [x for x in main if x.get(key) == v]))
    for v in sorted({x["split"] for x in main if x.get("split")}):
        lines.append(row(f"Test split: {v}", [x for x in main if x.get("split") == v]))
    base = b.get("baselines") or {}
    lines += ["", "## Baselines on the same odds", "",
              "| Strategy | Bets | Units | ROI |", "| --- | --- | --- | --- |"]
    for k, label in (("elo_favourite", "Back the Elo favourite, every match"), ("market_favourite", "Back the market favourite, every match"),
                     ("elo_favourite_same_matches", "Back the Elo favourite, only the matches Deuce bet")):
        s = base.get(k)
        if s and s.get("traded"):
            lines.append(f"| {label} | {s['traded']} | {units(s['profit'])} | {pct(s['return_per_match'], True)} |")
    mv = b.get("model_vs_market")
    if mv:
        lines += ["", f"Probability quality on {mv['n']} matches with odds: model Brier {mv['model_brier']:.4f} vs de-vigged market "
                      f"{mv['market_brier_devigged']:.4f} (lower is better); log loss {mv['model_log_loss']:.4f} vs "
                      f"{mv['market_log_loss_devigged']:.4f}. The market is usually the harder benchmark."]
    cum = b.get("cumulative") or []
    if cum:
        lines += ["", f"Cumulative result at the pre-set threshold: {units(cum[-1]['pnl'])} over {len(cum)} betting days "
                      f"(low {units(min(c['pnl'] for c in cum))}, high {units(max(c['pnl'] for c in cum))})."]
    lines += ["", "## Last 25 settled bets", "", "| Day | Match | Pick | Odds | Model prob | Edge | Result | Units |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for x in sorted(main, key=lambda r: r["date"], reverse=True)[:25]:
        pick = x["p1"] if x["pick"] == "p1" else x["p2"]
        lines.append(f"| {x['date']} | {x['p1']} v {x['p2']} ({x['tournament']}) | {pick} | {x['odds']:.2f} | "
                     f"{pct(x['prob'])} | {x['edge'] * 100:.1f} pts | {'Won' if x['won'] else 'Lost'} | {units(x['profit'])} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description="Write docs/tennis-paper-bets.md")
    ap.add_argument("--backtest", default=str(BACKTEST))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    p = Path(a.backtest)
    if not p.exists():
        raise SystemExit(f"No backtest at {p}. Run `python -m engine.backtest` first.")
    bt: dict[str, Any] = json.loads(p.read_text())
    odds_rows = None
    try:
        from .db import connect
        odds_rows = connect().execute("SELECT COUNT(*) FROM odds").fetchone()[0]
    except Exception:  # noqa: BLE001
        pass
    stamp = (bt.get("generated_at") or datetime.now(timezone.utc).isoformat())[:10]
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report(bt, stamp, odds_rows))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
